import { readdir, readFile, writeFile } from 'node:fs/promises';

// Package the original deck without maintaining a second copy of its content.
const root = new URL('../deck/', import.meta.url);
const types = { '.html': 'text/html; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg' };
const files = {};
async function collect(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const path = prefix + entry.name;
    const url = new URL(entry.name, directory);
    if (entry.isDirectory()) {
      await collect(new URL(entry.name + '/', directory), path + '/');
    } else {
      const extension = path.slice(path.lastIndexOf('.'));
      const type = types[extension];
      if (!type) throw new Error(`Unsupported deck asset: ${path}`);
      files['/' + path] = { type, data: (await readFile(url)).toString('base64') };
    }
  }
}
await collect(root);
await writeFile(new URL('../deck-assets.js', import.meta.url), `// Generated by scripts/build-deck.js; do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`Packaged ${Object.keys(files).length} deck files.`);

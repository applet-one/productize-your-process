// Embeds every file under input/ into generated/inputs.js so the app can serve them.
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join, relative } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const inputDir = join(root, "input");

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = [];
for (const full of (await walk(inputDir)).sort()) {
  files.push({ path: relative(inputDir, full), content: await readFile(full, "utf8") });
}
await mkdir(join(root, "generated"), { recursive: true });
await writeFile(
  join(root, "generated/inputs.js"),
  `// Generated by npm run build. Do not edit.\nexport const inputs = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`Embedded ${files.length} input files into generated/inputs.js`);
